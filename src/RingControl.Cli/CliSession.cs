using System.Net;
using System.Text;
using System.Text.Json;
using RingControl.Core.Api;
using RingControl.Core.Auth;
using RingControl.Core.Models;
using RingControl.Core.Platform;
using RingControl.Core.Security;

namespace RingControl.Cli;

/// <summary>
/// Authenticated Ring context for the CLI: loads the stored refresh token, refreshes it,
/// builds the API client and persists every rotated token so the daemon keeps working
/// across restarts.
/// </summary>
internal sealed class CliSession : IDisposable
{
    private readonly HttpClient _http;
    private readonly RingAuthClient _auth;
    private readonly SessionStore _store;
    private readonly RingApiClient _api;

    private CliSession(HttpClient http, RingAuthClient auth, SessionStore store, RingApiClient api,
        string hardwareId, string? email)
    {
        _http = http;
        _auth = auth;
        _store = store;
        _api = api;
        HardwareId = hardwareId;
        Email = email;
    }

    public RingApiClient Api => _api;

    public string HardwareId { get; }

    public string? Email { get; }

    public static HttpClient CreateHttp() => new(new SocketsHttpHandler
    {
        PooledConnectionLifetime = TimeSpan.FromMinutes(10),
        ConnectTimeout = TimeSpan.FromSeconds(20),
    })
    {
        Timeout = TimeSpan.FromSeconds(90),
    };

    public static string EnsureHardwareId()
    {
        var path = Path.Combine(PlatformPaths.ConfigDirectory, "hardware.id");

        try
        {
            if (File.Exists(path))
            {
                var existing = File.ReadAllText(path).Trim();
                if (Guid.TryParse(existing, out _))
                {
                    return existing;
                }
            }
        }
        catch
        {
            // Fall through and regenerate.
        }

        var hardwareId = ImportFromGuiSettings() ?? Guid.NewGuid().ToString();

        try
        {
            Directory.CreateDirectory(PlatformPaths.ConfigDirectory);
            File.WriteAllText(path, hardwareId);
        }
        catch
        {
            // Not fatal: Ring accepts a new hardware id, the session is simply re-created.
        }

        return hardwareId;
    }

    /// <summary>On Windows, reuse the hardware id generated by the desktop app so both share identity.</summary>
    private static string? ImportFromGuiSettings()
    {
        if (!OperatingSystem.IsWindows())
        {
            return null;
        }

        try
        {
            var settings = Path.Combine(PlatformPaths.ConfigDirectory, "settings.json");
            if (!File.Exists(settings))
            {
                return null;
            }

            using var document = JsonDocument.Parse(File.ReadAllText(settings));
            if (document.RootElement.TryGetProperty("HardwareId", out var value) &&
                value.ValueKind == JsonValueKind.String)
            {
                var hardwareId = value.GetString();
                return Guid.TryParse(hardwareId, out _) ? hardwareId : null;
            }
        }
        catch
        {
            // Ignore a malformed settings file.
        }

        return null;
    }

    public static CliSession Open()
    {
        var store = new SessionStore();
        var stored = store.Load()
                     ?? throw new CliException("No hay ninguna sesión de Ring guardada.\nEjecuta primero: ringcontrol login");

        var hardwareId = string.IsNullOrWhiteSpace(stored.HardwareId) ? EnsureHardwareId() : stored.HardwareId;
        var http = CreateHttp();
        var auth = new RingAuthClient(http, hardwareId);

        RingTokens tokens;
        try
        {
            tokens = auth.RefreshAsync(stored.RefreshToken).GetAwaiter().GetResult();
        }
        catch (RingAuthException ex)
        {
            http.Dispose();
            throw new CliException(ex.Message + "\nEjecuta: ringcontrol login", 3);
        }

        var api = new RingApiClient(http, auth, hardwareId, tokens);
        var session = new CliSession(http, auth, store, api, hardwareId, stored.Email);

        // Ring rotates refresh tokens on every refresh: persist the new one immediately,
        // otherwise a daemon restart would present a token that Ring already invalidated.
        session.Persist(tokens, stored.Email);

        api.TokensRefreshed += (_, refreshed) => session.Persist(refreshed, stored.Email);

        return session;
    }

    /// <summary>Signs in with email/password (+2FA) and stores only the refresh token.</summary>
    public static CliSession Login(string email, string password, string? twoFactorCode, TextWriter? output = null)
    {
        output ??= Console.Out;

        var store = new SessionStore();
        var hardwareId = EnsureHardwareId();
        var http = CreateHttp();
        var auth = new RingAuthClient(http, hardwareId);

        RingTokens tokens;
        try
        {
            tokens = auth.LoginAsync(email, password, twoFactorCode).GetAwaiter().GetResult();
        }
        catch (RingAuthException ex) when (ex.RequiresTwoFactor && string.IsNullOrWhiteSpace(twoFactorCode))
        {
            output.WriteLine("  " + (ex.Prompt ?? "Ring requiere un código de verificación."));

            var code = Console.IsInputRedirected
                ? Console.ReadLine()?.Trim()
                : Ui.PromptSecret("Código de verificación");

            if (string.IsNullOrWhiteSpace(code))
            {
                http.Dispose();
                throw new CliException("No se introdujo el código de verificación.", 3);
            }

            try
            {
                tokens = auth.LoginAsync(email, password, code).GetAwaiter().GetResult();
            }
            catch (RingAuthException retry)
            {
                http.Dispose();
                throw new CliException(retry.Message, 3);
            }
        }
        catch (RingAuthException ex)
        {
            http.Dispose();
            throw new CliException(ex.Message, 3);
        }

        var api = new RingApiClient(http, auth, hardwareId, tokens);
        var session = new CliSession(http, auth, store, api, hardwareId, email);
        session.Persist(tokens, email);

        api.TokensRefreshed += (_, refreshed) => session.Persist(refreshed, email);

        return session;
    }

    private void Persist(RingTokens tokens, string? email)
    {
        try
        {
            _store.Save(new StoredRingSession(tokens.RefreshToken, HardwareId, email));
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine("No se pudo guardar la sesión: " + ex.Message);
        }
    }

    public IReadOnlyList<RingDevice> GetDevices() => Api.GetDevicesAsync().GetAwaiter().GetResult();

    public RingDevice ResolveDevice(string? selector)
    {
        var devices = GetDevices();

        if (devices.Count == 0)
        {
            throw new CliException("La cuenta no tiene cámaras ni timbres Ring.");
        }

        if (string.IsNullOrWhiteSpace(selector) || selector is "0" or "first" or "primera")
        {
            if (devices.Count == 1)
            {
                return devices[0];
            }

            throw new CliException("Hay varias cámaras. Indica el ID o el nombre:\n" +
                                   string.Join("\n", devices.Select(d => $"  {d.Id}  {d.Name}")));
        }

        if (long.TryParse(selector, out var id))
        {
            var byId = devices.FirstOrDefault(d => d.Id == id);
            if (byId is not null)
            {
                return byId;
            }
        }

        var matches = devices
            .Where(d => d.Name.Contains(selector, StringComparison.CurrentCultureIgnoreCase))
            .ToList();

        return matches.Count switch
        {
            1 => matches[0],
            0 => throw new CliException($"No se encontró ninguna cámara que coincida con \"{selector}\"."),
            _ => throw new CliException($"\"{selector}\" coincide con varias cámaras. Usa el ID:\n" +
                                        string.Join("\n", matches.Select(d => $"  {d.Id}  {d.Name}"))),
        };
    }

    public void Dispose()
    {
        _api.Dispose();
        _http.Dispose();
    }
}
